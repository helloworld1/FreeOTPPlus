class OtpTokenDatabaseTest {

    @get:Rule
    val tempFolder = TemporaryFolder()

    private val openDatabases = mutableListOf<OtpTokenDatabase>()

    @After
    fun tearDown() {
        openDatabases.forEach { db -> runCatching { db.close() } }
        openDatabases.clear()
    }

    private fun createInMemoryDatabase(): OtpTokenDatabase {
        return Room.inMemoryDatabaseBuilder<OtpTokenDatabase>()
            .setDriver(BundledSQLiteDriver())
            .build()
            .also { openDatabases.add(it) }
    }

    private fun openMigratedFileDatabase(dbFile: File): OtpTokenDatabase {
        return Room.databaseBuilder<OtpTokenDatabase>(name = dbFile.absolutePath)
            .setDriver(BundledSQLiteDriver())
            .addMigrations(
                OtpTokenDatabase.MIGRATION_1_2,
                OtpTokenDatabase.MIGRATION_2_3,
                OtpTokenDatabase.MIGRATION_3_4
            )
            .build()
            .also { openDatabases.add(it) }
    }

    private fun sampleToken(
        id: Long = 0L,
        ordinal: Long = 0L,
        issuer: String? = "GitHub",
        label: String = "alice@example.com",
        imagePath: String? = null,
        tokenType: OtpTokenType = OtpTokenType.TOTP,
        algorithm: String = "SHA1",
        secret: String = "JBSWY3DPEHPK3PXP",
        digits: Int = 6,
        counter: Long = 0L,
        period: Int = 30,
        encryptionType: EncryptionType = EncryptionType.PLAIN_TEXT,
        categories: List<String> = emptyList()
    ) = OtpToken(
        id = id,
        ordinal = ordinal,
        issuer = issuer,
        label = label,
        imagePath = imagePath,
        tokenType = tokenType,
        algorithm = algorithm,
        secret = secret,
        digits = digits,
        counter = counter,
        period = period,
        encryptionType = encryptionType,
        categories = categories
    )

    @Test
    fun insertAndQuery_preservesAllFieldsTypeConvertersAndAutoGeneratedIds(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()

        dao.insert(
            sampleToken(
                id = 0L,
                ordinal = 10L,
                issuer = null,
                label = "no-issuer@example.com",
                imagePath = "builtin:GitHub",
                tokenType = OtpTokenType.HOTP,
                algorithm = "SHA512",
                secret = "v1:encryptedPayload==",
                digits = 8,
                counter = 77L,
                period = 60,
                encryptionType = EncryptionType.ENCRYPTED,
                categories = listOf("Work", "Cloud, \"Prod\"", "🔑 Vault")
            )
        )
        dao.insert(
            sampleToken(
                id = 0L,
                ordinal = 5L,
                issuer = "GitLab",
                label = "bob@gitlab.com"
            )
        )

        val all = dao.getAll().first()
        assertThat(all).hasSize(2)
        // Ordered strictly by ordinal (5L before 10L), with distinct auto-generated primary keys
        assertThat(all[0].issuer).isEqualTo("GitLab")
        assertThat(all[0].id).isEqualTo(2L)

        val richToken = all[1]
        assertThat(richToken.id).isEqualTo(1L)
        assertThat(richToken.ordinal).isEqualTo(10L)
        assertThat(richToken.issuer).isNull()
        assertThat(richToken.label).isEqualTo("no-issuer@example.com")
        assertThat(richToken.imagePath).isEqualTo("builtin:GitHub")
        assertThat(richToken.tokenType).isEqualTo(OtpTokenType.HOTP)
        assertThat(richToken.algorithm).isEqualTo("SHA512")
        assertThat(richToken.secret).isEqualTo("v1:encryptedPayload==")
        assertThat(richToken.digits).isEqualTo(8)
        assertThat(richToken.counter).isEqualTo(77L)
        assertThat(richToken.period).isEqualTo(60)
        assertThat(richToken.encryptionType).isEqualTo(EncryptionType.ENCRYPTED)
        assertThat(richToken.categories).containsExactly("Work", "Cloud, \"Prod\"", "🔑 Vault").inOrder()

        assertThat(dao.get(1L).first()).isEqualTo(richToken)
        assertThat(dao.get(999L).first()).isNull()
    }

    @Test
    fun getAll_emitsReactiveUpdatesAcrossInsertUpdateAndDelete(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()
        val observed = Channel<List<OtpToken>>(Channel.UNLIMITED)

        val collectorJob = launch {
            dao.getAll().collect { list ->
                observed.send(list)
            }
        }
        try {
            assertThat(withTimeout(5_000L) { observed.receive() }).isEmpty()

            dao.insert(sampleToken(id = 1L, ordinal = 1L, issuer = "First", label = "a"))
            assertThat(withTimeout(5_000L) { observed.receive() }.map { it.issuer })
                .containsExactly("First")

            dao.update(sampleToken(id = 1L, ordinal = 1L, issuer = "Updated", label = "a"))
            assertThat(withTimeout(5_000L) { observed.receive() }.map { it.issuer })
                .containsExactly("Updated")

            dao.deleteById(1L)
            assertThat(withTimeout(5_000L) { observed.receive() }).isEmpty()
        } finally {
            collectorJob.cancel()
        }
    }

    @Test
    fun getLastOrdinal_handlesEmptyNegativeUnorderedAndDeletedRows(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()

        assertThat(dao.getLastOrdinal()).isNull()

        dao.insert(sampleToken(id = 1L, ordinal = -10L))
        assertThat(dao.getLastOrdinal()).isEqualTo(-10L)

        dao.insertAll(
            listOf(
                sampleToken(id = 2L, ordinal = 42L),
                sampleToken(id = 3L, ordinal = 7L)
            )
        )
        assertThat(dao.getLastOrdinal()).isEqualTo(42L)

        dao.deleteById(2L)
        assertThat(dao.getLastOrdinal()).isEqualTo(7L)

        dao.deleteAll()
        assertThat(dao.getLastOrdinal()).isNull()
    }

    @Test
    fun insertConflictReplace_andReplaceAllTransaction_atomicallyOverwriteRows(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()

        dao.insert(sampleToken(id = 10L, ordinal = 1L, issuer = "Original", label = "user1"))
        dao.insert(sampleToken(id = 10L, ordinal = 2L, issuer = "Replaced", label = "user1_new"))

        assertThat(dao.getAll().first()).hasSize(1)
        assertThat(dao.get(10L).first()?.issuer).isEqualTo("Replaced")
        assertThat(dao.get(10L).first()?.ordinal).isEqualTo(2L)

        dao.replaceAll(
            listOf(
                sampleToken(id = 20L, ordinal = 0L, issuer = "BatchA", label = "a"),
                sampleToken(id = 21L, ordinal = 1L, issuer = "BatchB", label = "b")
            )
        )
        val afterReplaceAll = dao.getAll().first()
        assertThat(afterReplaceAll.map { it.id to it.issuer }).containsExactly(
            20L to "BatchA",
            21L to "BatchB"
        ).inOrder()
    }

    @Test
    fun updateAll_andUpdateOrdinal_modifyExpectedRowsOnly(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()
        val t1 = sampleToken(id = 1L, ordinal = 10L, issuer = "One", label = "u1")
        val t2 = sampleToken(id = 2L, ordinal = 20L, issuer = "Two", label = "u2")
        val t3 = sampleToken(id = 3L, ordinal = 30L, issuer = "Three", label = "u3")
        dao.insertAll(listOf(t1, t2, t3))

        dao.updateAll(
            listOf(
                t1.copy(label = "u1_edited"),
                t3.copy(label = "u3_edited")
            )
        )
        assertThat(dao.getAll().first().map { it.label })
            .containsExactly("u1_edited", "u2", "u3_edited").inOrder()

        dao.updateOrdinal(3L, 0L)
        assertThat(dao.getAll().first().map { it.id })
            .containsExactly(3L, 1L, 2L).inOrder()
    }

    @Test
    fun movePairs_swapsOrdinalsAcrossSingleChainedAndMissingIds(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()
        dao.insertAll(
            listOf(
                sampleToken(id = 1L, ordinal = 10L, issuer = "Alpha"),
                sampleToken(id = 2L, ordinal = 20L, issuer = "Beta"),
                sampleToken(id = 3L, ordinal = 30L, issuer = "Gamma")
            )
        )

        // Drag Alpha (1) down past Beta (2) and then past Gamma (3); include missing pair (99, 1) to verify safe skip
        dao.movePairs(listOf(1L to 2L, 99L to 1L, 1L to 3L))

        val moved = dao.getAll().first()
        assertThat(moved.map { it.issuer }).containsExactly("Beta", "Gamma", "Alpha").inOrder()
        assertThat(moved.map { it.ordinal }).containsExactly(10L, 20L, 30L).inOrder()
    }

    @Test
    fun incrementCounter_incrementsHotpCounterAndGuardsAgainstLongMaxValueOverflow(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()
        dao.insertAll(
            listOf(
                sampleToken(id = 1L, ordinal = 1L, tokenType = OtpTokenType.HOTP, counter = 0L),
                sampleToken(id = 2L, ordinal = 2L, tokenType = OtpTokenType.HOTP, counter = Long.MAX_VALUE - 1L)
            )
        )

        dao.incrementCounter(1L)
        dao.incrementCounter(1L)
        assertThat(dao.get(1L).first()?.counter).isEqualTo(2L)

        // Advance from Long.MAX_VALUE - 1 -> Long.MAX_VALUE, then verify subsequent increments saturate safely
        dao.incrementCounter(2L)
        assertThat(dao.get(2L).first()?.counter).isEqualTo(Long.MAX_VALUE)

        dao.incrementCounter(2L)
        assertThat(dao.get(2L).first()?.counter).isEqualTo(Long.MAX_VALUE)

        // Non-existent token ID is a safe no-op
        dao.incrementCounter(999L)
    }

    @Test
    fun sortAll_persistsAllFourSortOrdersAndHandlesZeroOrSingleTokenNoOp(): Unit = runBlocking {
        val dao = createInMemoryDatabase().otpTokenDao()

        // Empty and single-token tables are safe no-ops
        dao.sortAll(TokenSortOrder.ACCOUNT_ASC)
        dao.insert(sampleToken(id = 1L, ordinal = 50L, issuer = "Solo", label = "z@solo.io"))
        dao.sortAll(TokenSortOrder.ACCOUNT_ASC)
        assertThat(dao.get(1L).first()?.ordinal).isEqualTo(50L)

        dao.replaceAll(
            listOf(
                sampleToken(id = 1L, ordinal = 10L, issuer = "Slack", label = "zoe@slack.com"),
                sampleToken(id = 2L, ordinal = 20L, issuer = "Amazon", label = "amy@amazon.com"),
                sampleToken(id = 3L, ordinal = 30L, issuer = "github", label = "Mike@github.com")
            )
        )

        dao.sortAll(TokenSortOrder.ACCOUNT_ASC)
        assertThat(dao.getAll().first().map { it.label })
            .containsExactly("amy@amazon.com", "Mike@github.com", "zoe@slack.com").inOrder()

        dao.sortAll(TokenSortOrder.ACCOUNT_DESC)
        assertThat(dao.getAll().first().map { it.label })
            .containsExactly("zoe@slack.com", "Mike@github.com", "amy@amazon.com").inOrder()

        dao.sortAll(TokenSortOrder.ISSUER_ASC)
        assertThat(dao.getAll().first().map { it.issuer })
            .containsExactly("Amazon", "github", "Slack").inOrder()

        dao.sortAll(TokenSortOrder.ISSUER_DESC)
        assertThat(dao.getAll().first().map { it.issuer })
            .containsExactly("Slack", "github", "Amazon").inOrder()
    }

