    @Test
    fun writerTransaction_andClearAllTables_guaranteeAtomicityAndCleanReset(): Unit = runBlocking {
        val db = createInMemoryDatabase()
        val dao = db.otpTokenDao()
        dao.insert(sampleToken(id = 1L, ordinal = 1L, issuer = "Initial", label = "init"))

        assertThrows(IllegalStateException::class.java) {
            runBlocking {
                db.useWriterConnection { transactor ->
                    transactor.immediateTransaction {
                        dao.insert(sampleToken(id = 2L, ordinal = 2L, issuer = "Uncommitted", label = "temp"))
                        dao.deleteById(1L)
                        throw IllegalStateException("Abort transaction")
                    }
                }
            }
        }

        // Both the insert of id=2 and deletion of id=1 were rolled back atomically
        val remaining = dao.getAll().first()
        assertThat(remaining).hasSize(1)
        assertThat(remaining.single().id).isEqualTo(1L)
        assertThat(remaining.single().issuer).isEqualTo("Initial")

        db.clearAllTables()
        assertThat(dao.getAll().first()).isEmpty()
    }

    @Test
    fun migration1To4_fullChainFromV1Schema_preservesTokensAddsCategoriesAndNormalizesCounters(): Unit = runBlocking {
        val dbFile = File(tempFolder.newFolder("v1_migration"), "otp-v1.db")
        BundledSQLiteDriver().open(dbFile.absolutePath).use { conn ->
            conn.execSQL(
                """
                CREATE TABLE `otp_tokens` (
                    `id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
                    `ordinal` INTEGER NOT NULL,
                    `issuer` TEXT,
                    `label` TEXT NOT NULL,
                    `imagePath` TEXT,
                    `tokenType` TEXT NOT NULL,
                    `algorithm` TEXT NOT NULL,
                    `secret` TEXT NOT NULL,
                    `digits` INTEGER NOT NULL,
                    `counter` INTEGER NOT NULL,
                    `period` INTEGER NOT NULL,
                    `encryptionType` TEXT NOT NULL
                )
                """.trimIndent()
            )
            conn.execSQL(
                """
                INSERT INTO `otp_tokens` VALUES
                (1, 10, 'GitHub', 'alice', NULL, 'TOTP', 'SHA1', 'JBSWY3DPEHPK3PXP', 6, 0, 30, 'PLAIN_TEXT'),
                (2, 20, 'LegacyHotp', 'bob', 'builtin:GitHub', 'HOTP', 'SHA256', 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ', 8, -1, 30, 'PLAIN_TEXT'),
                (3, 30, 'ActiveHotp', 'carol', NULL, 'HOTP', 'SHA1', 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ', 6, 19, 30, 'PLAIN_TEXT')
                """.trimIndent()
            )
            conn.execSQL("PRAGMA user_version = 1")
        }

        val migratedDb = openMigratedFileDatabase(dbFile)
        val tokens = migratedDb.otpTokenDao().getAll().first()
        assertThat(tokens).hasSize(3)

        assertThat(tokens[0].issuer).isEqualTo("GitHub")
        assertThat(tokens[0].categories).isEmpty()
        assertThat(tokens[0].counter).isEqualTo(0L)

        // Legacy unused -1 HOTP counter normalized to 0; active synced HOTP counter 19 preserved
        assertThat(tokens[1].issuer).isEqualTo("LegacyHotp")
        assertThat(tokens[1].imagePath).isEqualTo("builtin:GitHub")
        assertThat(tokens[1].digits).isEqualTo(8)
        assertThat(tokens[1].counter).isEqualTo(0L)
        assertThat(tokens[1].categories).isEmpty()

        assertThat(tokens[2].issuer).isEqualTo("ActiveHotp")
        assertThat(tokens[2].counter).isEqualTo(19L)
    }

