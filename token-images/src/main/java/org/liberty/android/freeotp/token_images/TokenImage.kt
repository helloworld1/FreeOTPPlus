private fun containsCandidate(text: String, candidate: String, matchWordBoundary: Boolean): Boolean {
    if (!matchWordBoundary) {
        return text.contains(candidate, ignoreCase = true)
    }
    if (candidate.isEmpty()) return false
    var startIndex = 0
    while (true) {
        val idx = text.indexOf(candidate, startIndex, ignoreCase = true)
        if (idx < 0) return false
        val endIdx = idx + candidate.length
        val leftBoundary = idx == 0 || !text[idx - 1].isLetter()
        val rightBoundary = endIdx == text.length || !text[endIdx].isLetter()
        if (leftBoundary && rightBoundary) {
            return true
        }
        startIndex = idx + 1
    }
}

fun TokenImage.matchToken(issuer: String?, label: String?): Boolean {
    val primary = this.issuer ?: this.name
    val candidates = if (altIssuers.isEmpty()) {
        listOf(primary)
    } else {
        listOf(primary) + altIssuers
    }

    val issuerMatched = issuer != null && candidates.any { candidate ->
        containsCandidate(issuer, candidate, matchWordBoundary)
    }

    return if (!issuerMatched && this.alsoMatchLabel) {
        label != null && candidates.any { candidate ->
            containsCandidate(label, candidate, matchWordBoundary)
        }
    } else {
        issuerMatched
    }
}
